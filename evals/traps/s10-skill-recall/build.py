#!/usr/bin/env python3
"""Regenerate `pristine/descriptions.md` from the live skill frontmatters.

The fixture has to be the real routing surface, not a copy that drifts away
from it: a trap that measures selection against last month's descriptions
measures nothing. So the bundle is generated, and `--check` fails when the
checkout has moved past it (same contract as the prompt-surface census).

Usage:
    python3 build.py --write | --check
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
SKILLS = ROOT / "main" / "claude" / "skills"
BUNDLE = HERE / "pristine" / "descriptions.md"

HEADER = """<!-- GENERATED by build.py from main/claude/skills/*/SKILL.md. Do not edit. -->
# Resident skill descriptions

This is the whole routing surface a Claude session carries: for each installed
skill, the `name` and `description` from its frontmatter. Nothing else about a
skill is in context until it is selected.
"""


def description_block(skill_md: Path) -> str:
    """The `description:` value, whether it is a literal block or one line."""
    text = skill_md.read_text(encoding="utf-8")
    match = re.match(r"^---\n(.*?)\n---\n", text, re.DOTALL)
    if not match:
        raise SystemExit(f"{skill_md}: no frontmatter")
    frontmatter = match.group(1)
    block = re.search(r"^description: \|\n((?:[ \t]+.*\n?)+)", frontmatter,
                      re.MULTILINE)
    if block:
        lines = [line.strip() for line in block.group(1).rstrip().split("\n")]
        return "\n".join(lines)
    inline = re.search(r"^description: (.+)$", frontmatter, re.MULTILINE)
    if not inline:
        raise SystemExit(f"{skill_md}: no description")
    return inline.group(1).strip()


def render() -> str:
    parts = [HEADER]
    for directory in sorted(SKILLS.iterdir()):
        skill_md = directory / "SKILL.md"
        if not skill_md.is_file():
            continue
        parts.append(f"\n## {directory.name}\n\n{description_block(skill_md)}\n")
    return "".join(parts)


def main() -> int:
    ap = argparse.ArgumentParser()
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    fresh = render()
    if args.write:
        BUNDLE.parent.mkdir(parents=True, exist_ok=True)
        BUNDLE.write_text(fresh, encoding="utf-8")
        print(f"wrote {BUNDLE.relative_to(ROOT)}")
        return 0
    current = BUNDLE.read_text(encoding="utf-8") if BUNDLE.exists() else ""
    if current != fresh:
        print(f"stale fixture: {BUNDLE.relative_to(ROOT)}\n"
              f"refresh with: python3 {Path(__file__).relative_to(ROOT)} --write",
              file=sys.stderr)
        return 1
    print("fixture is current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
